use cc1::ast::{F80, Value};
use cc1::target::I386;

#[test]
fn f80_parses_decimal_constants() {
    let cases = [
        ("1.0", "0xK3FFF8000000000000000"),
        ("2.0", "0xK40008000000000000000"),
        ("0.5", "0xK3FFE8000000000000000"),
        ("2.5", "0xK4000A000000000000000"),
        ("3.3", "0xK4000D333333333333333"),
        ("0.1", "0xK3FFBCCCCCCCCCCCCCCCD"),
        ("1e10", "0xK40209502F90000000000"),
        ("1e-10", "0xK3FDDDBE6FECEBDEDD5BF"),
        ("123456789.123456789", "0xK4019EB79A2A3F35BA6E7"),
        ("3.14159265358979323846", "0xK4000C90FDAA22168C235"),
        ("1e100", "0xK414B924D692CA61BE758"),
        ("1e-100", "0xK3EB2DFF9772470297EBD"),
        ("1e300", "0xK43E3BF21E44003ACDD2D"),
        ("1e1000", "0xK4CF8F38DB1F9DD3DAC05"),
        ("1.7976931348623157e308", "0xK43FEFFFFFFFFFFFFF7AC"),
    ];
    for (src, bits) in cases {
        assert_eq!(format!("{:X}", F80::from(src)), bits, "F80::from({src:?})");
    }
}

#[test]
fn f80_keeps_the_bits_a_double_would_lose() {
    assert_eq!(
        format!("{:X}", F80::from("9007199254740993")),
        "0xK40348000000000000400"
    );
    assert_eq!(
        format!("{:X}", F80::from("18446744073709551615")),
        "0xK403EFFFFFFFFFFFFFFFF"
    );
    assert_eq!(i64::from(F80::from("9007199254740993")), 9007199254740993);
    assert_ne!(F80::from("1.0") + F80::from("1e-19"), F80::from("1.0"));
    assert_eq!(
        format!("{:X}", F80::from("1.0") + F80::from("1e-19")),
        "0xK3FFF8000000000000001"
    );
}

#[test]
fn f80_saturates_and_denormalises_at_the_extremes() {
    let cases = [
        ("1e4932", "0xK7FFED72CB2A95C7EF6CD"),
        ("1e4933", "0xK7FFF8000000000000000"),
        ("1e-4932", "0xK0000261247C8F29357F0"),
        ("1e-4950", "0xK00000000000000000003"),
        ("3.6e-4951", "0xK00000000000000000001"),
        ("1e-4951", "0xK00000000000000000000"),
        ("1e-5000", "0xK00000000000000000000"),
    ];
    for (src, bits) in cases {
        assert_eq!(format!("{:X}", F80::from(src)), bits, "F80::from({src:?})");
    }
    assert!(F80::from("1e4933").is_infinite());
    assert!(F80::from("1e-5000").is_zero());
}

#[test]
fn f80_arithmetic_rounds_once_to_nearest_even() {
    let cases = [
        ("1.5", '+', "1.5", "0xK4000C000000000000000"),
        ("1.0", '/', "3.0", "0xK3FFDAAAAAAAAAAAAAAAB"),
        ("0.1", '+', "0.2", "0xK3FFD999999999999999A"),
        ("1e100", '*', "1e-100", "0xK3FFEFFFFFFFFFFFFFFFF"),
        ("2.0", '*', "3.0", "0xK4001C000000000000000"),
        ("1.0", '*', "3.0", "0xK4000C000000000000000"),
        ("1.0", '-', "3.0", "0xKC0008000000000000000"),
        ("1e300", '*', "1e300", "0xK47C88EB39714297EFB28"),
        ("3.3", '*', "3.3", "0xK4002AE3D70A3D70A3D70"),
        ("1e-4930", '/', "1e10", "0xK00000000000663278E62"),
    ];
    for (lhs, op, rhs, bits) in cases {
        let (a, b) = (F80::from(lhs), F80::from(rhs));
        let got = match op {
            '+' => a + b,
            '-' => a - b,
            '*' => a * b,
            _ => a / b,
        };
        assert_eq!(format!("{got:X}"), bits, "{lhs} {op} {rhs}");
    }
}

#[test]
fn f80_handles_infinities_and_nans() {
    let one = F80::from("1.0");
    let zero = F80::from("0.0");
    assert!((one / zero).is_infinite());
    assert!(!(one / zero).is_negative());
    assert!((-one / zero).is_negative());
    assert!((zero / zero).is_nan());
    assert!((one / zero - one / zero).is_nan());
    assert!(((one / zero) * zero).is_nan());
    assert_eq!(format!("{:X}", F80::from("1e4933") + one), "0xK7FFF8000000000000000");
    assert!(zero / zero != zero / zero);
    assert_eq!(one.partial_cmp(&(zero / zero)), None);

    let (inf, two) = (one / zero, F80::from("2.0"));
    assert!((one + inf).is_infinite());
    assert!((inf + one).is_infinite());
    assert!((inf * two).is_infinite());
    assert!((inf / two).is_infinite());
    assert!((inf / inf).is_nan());
    assert_eq!(format!("{:X}", one / inf), "0xK00000000000000000000");
    assert_eq!(format!("{:X}", -one / inf), "0xK80000000000000000000");
}

#[test]
fn f80_handles_zero_operands() {
    let (one, zero) = (F80::from("1.0"), F80::from("0.0"));
    assert!(F80::from(0u64).is_zero());
    assert!(F80::from(0i64).is_zero());
    assert_eq!(format!("{:X}", zero + zero), "0xK00000000000000000000");
    assert_eq!(format!("{:X}", -zero + -zero), "0xK80000000000000000000");
    assert_eq!(format!("{:X}", zero + -zero), "0xK00000000000000000000");
    assert_eq!(format!("{:X}", one + zero), format!("{:X}", one));
    assert_eq!(format!("{:X}", zero + one), format!("{:X}", one));
    assert!((zero * one).is_zero());
    assert!((zero / one).is_zero());
}

#[test]
fn f80_converts_across_the_other_representations() {
    assert_eq!(format!("{:X}", F80::from(1.0)), "0xK3FFF8000000000000000");
    assert_eq!(format!("{:X}", F80::from(3.3)), format!("{:X}", F80::from(3.3)));
    assert_eq!(format!("{:X}", F80::from(1u64)), "0xK3FFF8000000000000000");
    assert_eq!(format!("{:X}", F80::from(-1i64)), "0xKBFFF8000000000000000");
    assert_eq!(format!("{:X}", F80::from(u64::MAX)), "0xK403EFFFFFFFFFFFFFFFF");
    assert_eq!(f64::from(F80::from("1.0")), 1.0);
    assert_eq!(f64::from(F80::from("3.3")), 3.3);
    assert_eq!(f64::from(F80::from("1e300")), 1e300);
    assert_eq!(f64::from(F80::from("1e1000")), f64::INFINITY);
    assert_eq!(i64::from(F80::from("3.9")), 3);
    assert_eq!(i64::from(-F80::from("3.9")), -3);
    assert_eq!(u64::from(F80::from("3.9")), 3);
    assert_eq!(f64::from(F80::from("0.0")), 0.0);
}

#[test]
fn f80_orders_and_compares() {
    let (one, two) = (F80::from("1.0"), F80::from("2.0"));
    assert!(one < two);
    assert!(-one < one);
    assert!(-one < F80::from("0.0"));
    assert_eq!(F80::from("0.0"), -F80::from("0.0"));
    assert_eq!(one, F80::from("1.0"));
    assert!(F80::from("1e-4950") > F80::from("0.0"));
}

#[test]
fn a_long_double_literal_reaches_value_as_f80() {
    let Value::LongDouble(v) = Value::parse("3.3l", &I386).res else {
        panic!("expected a long double");
    };
    assert_eq!(format!("{v:X}"), "0xK4000D333333333333333");
    assert_eq!(Value::parse("1.0", &I386).res, Value::Double(1.0));
}

// ---- special values ------------------------------------------------------

#[test]
fn f80_propagates_nan_through_every_operation() {
    let (one, zero) = (F80::from("1.0"), F80::from("0.0"));
    let nan = zero / zero;
    assert!((nan + one).is_nan());
    assert!((one + nan).is_nan());
    assert!((nan - one).is_nan());
    assert!((one - nan).is_nan());
    assert!((nan * one).is_nan());
    assert!((one * nan).is_nan());
    assert!((nan / one).is_nan());
    assert!((one / nan).is_nan());
    assert!((-nan).is_nan());
    assert!(!nan.is_finite());
    assert!(!nan.is_infinite());
    assert!(!nan.is_negative());
}

#[test]
fn f80_overflows_to_infinity_from_arithmetic() {
    let huge = F80::from("1e4932");
    assert!(huge.is_finite());
    assert!((huge + huge).is_infinite());
    assert!((huge * F80::from("10.0")).is_infinite());
    assert!((-huge - huge).is_infinite());
    assert!((-huge - huge).is_negative());
}

// ---- 6.2.1.4 rounding at the boundaries ----------------------------------

#[test]
fn f80_cancels_exactly() {
    let x = F80::from("3.3");
    assert!((x - x).is_zero());
    assert!(!(x - x).is_negative());
    let stepped = F80::from("1.0") + F80::from("1e-19");
    assert_eq!(format!("{:X}", stepped - F80::from("1.0")), "0xK3FC08000000000000000");
    assert_eq!(
        format!("{:X}", F80::from("1.0") - F80::from("1e-30")),
        "0xK3FFF8000000000000000"
    );
}

#[test]
fn f80_rounds_a_carry_out_into_the_next_exponent() {
    assert_eq!(
        format!("{:X}", F80::from("18446744073709551615.5")),
        "0xK403F8000000000000000"
    );
    assert_eq!(
        format!("{:X}", F80::from("18446744073709551615.5")),
        format!("{:X}", F80::from("18446744073709551616"))
    );
    assert_eq!(
        format!("{:X}", F80::from(u64::MAX) + F80::from("0.5")),
        "0xK403F8000000000000000"
    );
}

#[test]
fn f80_rounds_across_the_denormal_boundary() {
    assert_eq!(
        format!("{:X}", F80::from("336210314311209350617154782902e-4961")),
        "0xK00018000000000000000"
    );
    assert_eq!(
        format!("{:X}", F80::from("336210314311209350598928785243e-4961")),
        "0xK00007FFFFFFFFFFFFFFF"
    );
}

#[test]
fn f80_computes_with_denormals() {
    let small = F80::from("1e-4950");
    assert!(!small.is_zero());
    assert!(small.is_finite());
    assert_eq!(format!("{:X}", small + small), "0xK00000000000000000006");
    assert_eq!(format!("{:X}", small * F80::from("1e10")), "0xK000000000006FC23AC00");
    assert_eq!(f64::from(small), 0.0);
    assert_eq!(i64::from(small), 0);
    assert!(small < F80::from("1e-4940"));
    assert!(small > F80::from("0.0"));
}

// ---- 6.2.1.3 conversions -------------------------------------------------

#[test]
fn f80_saturates_integer_conversions() {
    let nan = F80::from("0.0") / F80::from("0.0");
    assert_eq!(i64::from(nan), 0);
    assert_eq!(u64::from(nan), 0);

    assert_eq!(i64::from(F80::from("1e40")), i64::MAX);
    assert_eq!(i64::from(-F80::from("1e40")), i64::MIN);
    assert_eq!(u64::from(F80::from("1e40")), u64::MAX);

    assert_eq!(i64::from(F80::from("1e30")), i64::MAX);
    assert_eq!(i64::from(-F80::from("1e30")), i64::MIN);
    assert_eq!(u64::from(F80::from("1e30")), u64::MAX);

    assert_eq!(i64::from(F80::from("1e4933")), i64::MAX);
    assert_eq!(i64::from(-F80::from("1e4933")), i64::MIN);
    assert_eq!(u64::from(F80::from("1e4933")), u64::MAX);

    assert_eq!(u64::from(-F80::from("1.0")), 0);
    assert_eq!(i64::from(F80::from("1e-50")), 0);
    assert_eq!(i64::from(-F80::from("0.9")), 0);

    assert_eq!(i64::from(F80::from(i64::MIN)), i64::MIN);
    assert_eq!(i64::from(F80::from(i64::MAX)), i64::MAX);
    assert_eq!(u64::from(F80::from(u64::MAX)), u64::MAX);
}

#[test]
fn f80_converts_specials_to_and_from_f64() {
    assert!(F80::from(f64::NAN).is_nan());
    assert!(F80::from(f64::INFINITY).is_infinite());
    assert!(!F80::from(f64::INFINITY).is_negative());
    assert!(F80::from(f64::NEG_INFINITY).is_infinite());
    assert!(F80::from(f64::NEG_INFINITY).is_negative());
    assert!(F80::from(-0.0f64).is_zero());
    assert_eq!(
        format!("{:X}", F80::from(f64::MIN_POSITIVE / 2.0)),
        "0xK3C008000000000000000"
    );

    let (one, zero) = (F80::from("1.0"), F80::from("0.0"));
    assert!(f64::from(zero / zero).is_nan());
    assert_eq!(f64::from(one / zero), f64::INFINITY);
    assert_eq!(f64::from(-one / zero), f64::NEG_INFINITY);
    assert_eq!(f64::from(-F80::from("3.3")), -3.3);
    assert_eq!(f64::from(F80::from("1e-4000")), 0.0);
    assert_eq!(f64::from(F80::from("1e4000")), f64::INFINITY);
    assert!(f64::from(-zero).is_sign_negative());
}

#[test]
fn f80_orders_negatives() {
    let (one, two) = (F80::from("1.0"), F80::from("2.0"));
    assert!(-two < -one);
    assert!(-one > -two);
    assert!(one > -one);
    assert!(-one < one);
    assert!(-one < F80::from("0.0"));
    assert!(F80::from("0.0") > -one);

    let nan = F80::from("0.0") / F80::from("0.0");
    assert!(!(nan < one));
    assert!(!(nan > one));
    assert!(nan != one);
}

