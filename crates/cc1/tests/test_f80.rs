#[test]
fn f80_arithmetic_matches_the_oracle() {
    for (lhs, op, rhs, bits) in OPERATIONS {
        let (x, y) = (F80::from(lhs), F80::from(rhs));
        let got = match op {
            '+' => x + y,
            '-' => x - y,
            '*' => x * y,
            _ => x / y,
        };
        assert_eq!(format!("{got:X}"), bits, "{lhs} {op} {rhs}");
    }
}
